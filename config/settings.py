def env_bool(name: str, default: bool = False) -> bool:
    """Return a boolean environment variable, accepting common truthy spellings."""
    value = os.environ.get(name)
    if value is None or value.strip() == "":
        return default
    return value.strip().lower() in {"1", "true", "yes", "on"}


def env_int(name: str, default: int) -> int:
    """Return an integer environment variable, falling back to ``default``."""
    value = os.environ.get(name)
    if value is None or value.strip() == "":
        return default
    return int(value)


def env_float(name: str, default: float) -> float:
    """Return a float environment variable, falling back to ``default``."""
    value = os.environ.get(name)
    if value is None or value.strip() == "":
        return default
    return float(value)


def env_list(name: str, default: list[str] | None = None) -> list[str]:
    """Return a comma-separated environment variable as a list of strings."""
    value = os.environ.get(name)
    if not value:
        return list(default or [])
    return [item.strip() for item in value.split(",") if item.strip()]


